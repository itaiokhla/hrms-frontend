/* ------------------------------------------------------------------ actors */
type Place = { latitude: number; longitude: number; accuracy: number };

/**
 * A stand-in for a device's location receiver. Chrome's geolocation emulation keeps the timestamp
 * from when the position was set, so a later `maximumAge: 0` request gets an ever older fix (and the
 * app rightly refuses it). Re-emitting the current position every few seconds gives fresh fixes,
 * like real hardware does.
 */
export interface FakeGps {
  move: (place: Place) => Promise<void>;
  pause: () => void;
  resume: () => void;
}

export interface Actor {
  name: string;
  context: BrowserContext;
  page: Page;
  gps: FakeGps;
  /** Take the browser offline; network errors are expected only while it is. */
  setOffline: (offline: boolean) => Promise<void>;
  consoleErrors: string[];
  pageErrors: string[];
  apiDenials: string[];
  cdp: () => Promise<CDPSession>;
  close: () => Promise<void>;
}

/** Network 4xx/5xx the tests provoke on purpose are logged by Chrome as console errors; keep them apart. */
const EXPECTED_HTTP = /Failed to load resource: the server responded with a status of (4\d\d)/;

export async function actor(
  browser: Browser,
  testInfo: TestInfo,
  name: string,
  email: string | null,
  options: { geolocation?: { latitude: number; longitude: number; accuracy: number }; grantLocation?: boolean;
    viewport?: { width: number; height: number }; isMobile?: boolean; password?: string } = {},
): Promise<Actor> {
  const grant = options.grantLocation ?? !!options.geolocation;
  const context = await browser.newContext({
    baseURL: testInfo.project.use.baseURL,
    viewport: options.viewport ?? { width: 1360, height: 860 },
    isMobile: options.isMobile,
    hasTouch: options.isMobile,
    geolocation: options.geolocation,
    permissions: grant ? ["camera", "geolocation"] : ["camera"],
    recordVideo: { dir: testInfo.outputPath(`video-${name.replace(/\W+/g, "-")}`), size: { width: 1280, height: 800 } },
  });
  const page = await context.newPage();
  const consoleErrors: string[] = [];
  const pageErrors: string[] = [];
  const apiDenials: string[] = [];
  page.on("pageerror", (e) => pageErrors.push(e.message));
  let offline = false;
  page.on("console", (msg) => {
    if (msg.type() !== "error") return;
    if (EXPECTED_HTTP.test(msg.text())) apiDenials.push(msg.text());
    else if (offline && /net::ERR_INTERNET_DISCONNECTED/.test(msg.text())) apiDenials.push(`(offline) ${msg.text()}`);
    else consoleErrors.push(msg.text());
  });
  let session: CDPSession | null = null;
  let place: Place | undefined = options.geolocation;
  let ticker: ReturnType<typeof setInterval> | null = null;
  const emit = () => {
    if (place) context.setGeolocation(place).catch(() => undefined);
  };
  const gps: FakeGps = {
    move: async (next) => {
      place = next;
      await context.setGeolocation(next);
    },
    pause: () => {
      if (ticker) clearInterval(ticker);
      ticker = null;
    },
    resume: () => {
      if (ticker || !place) return;
      emit();
      ticker = setInterval(emit, 10_000);
    },
  };
  gps.resume();
  const a: Actor = {
    name, context, page, gps, consoleErrors, pageErrors, apiDenials,
    setOffline: async (value) => {
      if (value) offline = true;
      await context.setOffline(value);
      // Requests that were in flight report their failure just after reconnecting.
      if (!value) setTimeout(() => (offline = false), 2_000);
    },
    cdp: async () => (session ??= await context.newCDPSession(page)),
    close: async () => {
      gps.pause();
      const video = page.video();
      await context.close();
      if (video) await testInfo.attach(`video – ${name}`, { path: await video.path(), contentType: "video/webm" });
      await testInfo.attach(`console – ${name}`, {
        body: JSON.stringify({ consoleErrors, pageErrors, expectedApiDenials: apiDenials }, null, 2), contentType: "application/json",
      });
      expect(pageErrors, `uncaught page errors in ${name}'s browser`).toEqual([]);
      expect(consoleErrors, `unexpected console errors in ${name}'s browser`).toEqual([]);
    },
  };
  if (email) await login(page, email, options.password ?? secrets().password);
  return a;
}

const permissionSessions = new WeakMap<Actor, CDPSession>();

/**
 * Real Chrome permission state for this context's origin (CDP Browser.setPermission).
 * Chrome drops overrides when the DevTools session that set them detaches, so the
 * session stays open for the rest of the actor's life.
 */
export async function setLocationPermission(browser: Browser, a: Actor, setting: "granted" | "denied" | "prompt") {
  const origin = new URL(a.page.url()).origin;
  const { targetInfo } = await (await a.cdp()).send("Target.getTargetInfo");
  let session = permissionSessions.get(a);
  if (!session) {
    session = await browser.newBrowserCDPSession();
    permissionSessions.set(a, session);
  }
  await session.send("Browser.setPermission", {
    permission: { name: "geolocation" }, setting, origin, browserContextId: targetInfo.browserContextId,
  });
}

/** The API from inside the signed-in page, exactly as a user or tampering script could call it. */
export async function call<T = any>(page: Page, method: string, apiPath: string, body?: unknown) {
  return page.evaluate(
    async ({ method, apiPath, body }) => {
      const csrf = document.cookie.split("; ").find((c) => c.startsWith("hrms_csrf="))?.split("=")[1];
      const res = await fetch(`/api/v1${apiPath}`, {
        method, credentials: "include",
        headers: { "Content-Type": "application/json", ...(csrf ? { "X-CSRF-Token": decodeURIComponent(csrf) } : {}) },
        body: body === undefined ? undefined : JSON.stringify(body),
      });
      let data: unknown = null;
      try {
        data = await res.json();
      } catch {
        data = null;
      }
      return { status: res.status, data: data as T };
    },
    { method, apiPath, body },
  );
}

