/* ------------------------------------------------------------------ database */
export function db<T = Record<string, unknown>>(query: string, params: Record<string, string | number> = {}): T[] {
  const args = [path.join(BACKEND, "scripts", "e2e_db.py"), query, ...Object.entries(params).map(([k, v]) => `${k}=${v}`)];
  const out = execFileSync(PYTHON, args, { cwd: BACKEND, env: { ...process.env, E2E_PG_DATA: DATA_DIR }, encoding: "utf8" });
  return JSON.parse(out) as T[];
}

/** What a scheduled job does: detect expired shifts and missed checks (it cannot obtain a position). */
export function runSweep(): string {
  return execFileSync(PYTHON, [path.join(BACKEND, "scripts", "e2e_sweep.py"), "--data-dir", DATA_DIR], {
    cwd: BACKEND, encoding: "utf8",
  });
}

