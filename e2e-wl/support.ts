export interface Tenant {
  name: string;
  origin: string;
  context: BrowserContext;
  page: Page;
  requests: string[];
  failed: { url: string; error: string }[];
  console: { type: string; text: string }[];
  errors: string[];
  close: () => Promise<void>;
}

/**
 * An isolated Chrome profile (its own cookies and storage) on one tenant host. Every request,
 * failed request and console message is recorded so the test can prove no cross-host traffic.
 */
export async function openTenant(
  browser: Browser,
  testInfo: TestInfo,
  name: string,
  origin: string,
  options: { viewport?: { width: number; height: number }; colorScheme?: "light" | "dark"; isMobile?: boolean; userAgent?: string } = {},
): Promise<Tenant> {
  const context = await browser.newContext({
    baseURL: origin,
    viewport: options.viewport ?? { width: 1400, height: 880 },
    colorScheme: options.colorScheme ?? "light",
    isMobile: options.isMobile,
    hasTouch: options.isMobile,
    userAgent: options.userAgent,
    recordVideo: { dir: testInfo.outputPath(`video-${name.replace(/\W+/g, "-")}`), size: { width: 1280, height: 800 } },
  });
  const page = await context.newPage();
  const tenant: Tenant = {
    name, origin, context, page, requests: [], failed: [], console: [], errors: [],
    close: async () => {
      const video = page.video();
      await context.close();
      if (video) await testInfo.attach(`video – ${name}`, { path: await video.path(), contentType: "video/webm" });
      fs.writeFileSync(evidencePath(`${name.replace(/\W+/g, "-")}-network-console.json`), JSON.stringify({
        origin, requests: [...new Set(tenant.requests)], failed: tenant.failed, console: tenant.console, errors: tenant.errors,
      }, null, 2));
    },
  };
  context.on("request", (r: Request) => tenant.requests.push(r.url()));
  context.on("requestfailed", (r: Request) => tenant.failed.push({ url: r.url(), error: r.failure()?.errorText ?? "" }));
  page.on("console", (m) => tenant.console.push({ type: m.type(), text: m.text() }));
  page.on("pageerror", (e) => tenant.errors.push(e.message));
  return tenant;
}

export async function signIn(page: Page, email: string, password: string) {
  await page.goto("/login");
  await page.locator("#email").fill(email);
  await page.locator("#password").fill(password);
  await page.getByRole("button", { name: /sign in/i }).click();
  await page.waitForURL(/\/dashboard/, { timeout: 30_000 });
  await expect(page.getByRole("navigation", { name: "Main" })).toBeVisible();
}

/** Call the API from inside the signed-in browser, exactly as a tampering user could. */
export async function api<T = any>(page: Page, method: string, apiPath: string, body?: unknown): Promise<{ status: number; data: T }> {
  return page.evaluate(
    async ({ method, apiPath, body }) => {
      const csrf = document.cookie.split("; ").find((c) => c.startsWith("hrms_csrf="))?.split("=")[1];
      const res = await fetch(`/api/v1${apiPath}`, {
        method,
        credentials: "include",
        headers: { "Content-Type": "application/json", ...(csrf ? { "X-CSRF-Token": decodeURIComponent(csrf) } : {}) },
        body: body === undefined ? undefined : JSON.stringify(body),
      });
      let data: unknown = null;
      try {
        data = await res.json();
      } catch {
        data = null;
      }
      return { status: res.status, data };
    },
    { method, apiPath, body },
  ) as Promise<{ status: number; data: T }>;
}

/** The CSS custom property as the browser computed it on <html>. */
export async function cssVar(page: Page, name: string): Promise<string> {
  return page.evaluate((n) => getComputedStyle(document.documentElement).getPropertyValue(n).trim(), name);
}

/** Hosts this context talked to (must only be its own). */
export function hostsOf(tenant: Tenant): string[] {
  return [...new Set(tenant.requests.filter((u) => u.startsWith("http")).map((u) => new URL(u).host))];
}
