/** Credentials generated by scripts/seed_saas_three_companies.py for this run (git-ignored). */
export function secrets(): Secrets {
  const file = process.env.E2E_SAAS_SECRETS ?? path.join(BACKEND, ".local-secrets", "saas-e2e.json");
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

