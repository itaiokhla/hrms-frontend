/** A synthetic PNG logo (drawn by Pillow) for upload tests. */
export function makePng(text: string, colour: string, width = 640, height = 160): Buffer {
  const script = [
    "import io,sys,base64",
    "from PIL import Image, ImageDraw, ImageFont",
    `img=Image.new('RGBA',(${width},${height}),(0,0,0,0))`,
    "d=ImageDraw.Draw(img)",
    `c=tuple(int('${colour}'[i:i+2],16) for i in (1,3,5))`,
    `d.rounded_rectangle((10,10,${height}-10,${height}-10),radius=24,fill=c+(255,))`,
    `f=ImageFont.truetype('app/assets/fonts/NotoSans-Bold.ttf',${Math.round(height * 0.4)})`,
    `d.text((${height}+10,${height}//2),'${text}',font=f,fill=c+(255,),anchor='lm')`,
    "out=io.BytesIO(); img.save(out,'PNG'); sys.stdout.write(base64.b64encode(out.getvalue()).decode())",
  ].join("\n");
  return Buffer.from(execFileSync(PYTHON, ["-c", script], { cwd: BACKEND, encoding: "utf8" }), "base64");
}

export function sha256(data: Buffer): string {
  return crypto.createHash("sha256").update(data).digest("hex");
}

export function evidencePath(name: string): string {
  fs.mkdirSync(EVIDENCE, { recursive: true });
  return path.join(EVIDENCE, name);
}

