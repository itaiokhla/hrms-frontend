/** Record status codes for the evidence file and the report. */
export function writeEvidence(name: string, data: unknown) {
  fs.writeFileSync(evidencePath(name), JSON.stringify(data, null, 2));
}

/** A signed-in browser's API call, recorded as {method path -> status}. */
export async function probe(page: Page, log: Record<string, number>, method: string, apiPath: string, body?: unknown) {
  const { status } = await api(page, method, apiPath, body);
  log[`${method} ${apiPath}`] = status;
  return status;
}

/** True when nothing on the page is wider than the viewport (no sideways scrolling). */
export async function noHorizontalOverflow(page: Page): Promise<boolean> {
  return page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1);
}
